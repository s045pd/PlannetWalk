function hashSite(seed: number, cx: number, cz: number): number {
  let h = seed ^ (cx * 374761393) ^ (cz * 668265263);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return (h ^ (h >>> 16)) >>> 0;
}

/** 站点(cell) + 槽位 → 日志索引，种子确定性；同站点不同槽位保证不同 */
export function pickLogForSite(seed: number, cx: number, cz: number, slot: number): number {
  return (hashSite(seed, cx, cz) + slot * 7) % LOGS.length;
}

/** 收集状态：不可变添加 */
export function addCollected(collected: ReadonlySet<string>, id: string): Set<string> {
  const next = new Set(collected);
  next.add(id);
  return next;
}
